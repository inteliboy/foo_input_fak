// Adds a "FAK" entry to the Converter's output-format list on first start, pointing at the fak.exe
// shipped next to this DLL, so encoding works without setting up a custom encoder by hand.
//
// The desktop Converter (foo_converter) does not use the SDK's fb2k::audioEncoder service; its list
// is the configStore blob "converter.formats" (layout found by inspection of v2.25.10, not documented):
//   u32 count, then per entry: GUID type, u32 size, size bytes of payload.
//   Command-line encoders have type guid_cli; their payload starts with the encoder kind GUID.
//   The "Custom" kind (guid_custom) continues with: u32 highest bps, u32 lossless flag, then
//   strings (u32 length + UTF-8) name, encoder path, extension, parameters, u32 bitrate
//   (0xFFFFFFFF = none), string settings text, u32 flags.
// The blob is absent until the user first edits the list; the Converter then shows its built-in
// defaults, reproduced below (v2.25.10) so that adding FAK does not remove them.
//
// Runs once per profile (flag "foo_input_fak.converterPreset"): if the user deletes the entry it
// stays deleted. Later starts only repair the path of an existing FAK entry whose fak.exe is gone
// (component moved or reinstalled elsewhere). Anything unexpected in the blob: leave it untouched.

