constexpr uint32_t default_count = 18;

struct entry { GUID type; std::vector<uint8_t> payload; };

class reader {
public:
    reader(const uint8_t* p, size_t n) : m_p(p), m_n(n) {}
    bool u32(uint32_t& v) { if (m_n - m_pos < 4) return false; memcpy(&v, m_p + m_pos, 4); m_pos += 4; return true; }
    bool guid(GUID& g) { if (m_n - m_pos < 16) return false; memcpy(&g, m_p + m_pos, 16); m_pos += 16; return true; }
    bool bytes(size_t n, const uint8_t*& out) { if (m_n - m_pos < n) return false; out = m_p + m_pos; m_pos += n; return true; }
    bool str(std::string& s) { uint32_t n; const uint8_t* b; if (!u32(n) || !bytes(n, b)) return false; s.assign((const char*)b, n); return true; }
    bool done() const { return m_pos == m_n; }
private:
    const uint8_t* m_p; size_t m_n; size_t m_pos = 0;
};

void put_u32(std::vector<uint8_t>& o, uint32_t v) { o.insert(o.end(), (uint8_t*)&v, (uint8_t*)&v + 4); }
void put_guid(std::vector<uint8_t>& o, const GUID& g) { o.insert(o.end(), (const uint8_t*)&g, (const uint8_t*)&g + 16); }
void put_str(std::vector<uint8_t>& o, const std::string& s) { put_u32(o, (uint32_t)s.size()); o.insert(o.end(), s.begin(), s.end()); }

bool parse_list(const uint8_t* p, size_t n, uint32_t count, std::vector<entry>& out) {
    reader r(p, n);
    for (uint32_t i = 0; i < count; ++i) {
        entry e; uint32_t size; const uint8_t* b;
        if (!r.guid(e.type) || !r.u32(size) || !r.bytes(size, b)) return false;
        e.payload.assign(b, b + size);
        out.push_back(std::move(e));
    }
    return r.done();
}

struct custom_encoder {
    uint32_t bps = 24, lossless = 1;
    std::string name, path, ext, params;
    uint32_t bitrate = 0xFFFFFFFF;
    std::string settings;
    uint32_t flags = 0;
};

bool parse_custom(const entry& e, custom_encoder& c) {
    if (e.type != guid_cli) return false;
    reader r(e.payload.data(), e.payload.size());
    GUID kind;
    return r.guid(kind) && kind == guid_custom && r.u32(c.bps) && r.u32(c.lossless) && r.str(c.name) && r.str(c.path)
        && r.str(c.ext) && r.str(c.params) && r.u32(c.bitrate) && r.str(c.settings) && r.u32(c.flags) && r.done();
}

entry make_custom(const custom_encoder& c) {
    entry e{ guid_cli, {} };
    auto& o = e.payload;
    put_guid(o, guid_custom);
    put_u32(o, c.bps); put_u32(o, c.lossless);
    put_str(o, c.name); put_str(o, c.path); put_str(o, c.ext); put_str(o, c.params);
    put_u32(o, c.bitrate); put_str(o, c.settings); put_u32(o, c.flags);
    return e;
}

bool is_fak_exe(const std::string& path) {
    const size_t slash = path.find_last_of("\\/");
    return pfc::stringEqualsI_ascii(path.c_str() + (slash == std::string::npos ? 0 : slash + 1), "fak.exe");
}

bool file_exists(const std::string& utf8) {
    const DWORD a = GetFileAttributesW(pfc::stringcvt::string_wide_from_utf8(utf8.c_str()));
    return a != INVALID_FILE_ATTRIBUTES && !(a & FILE_ATTRIBUTE_DIRECTORY);
}

void install_preset() {
    std::string exe = core_api::get_my_full_path();
    const size_t slash = exe.find_last_of("\\/");
    if (slash == std::string::npos) return;
    exe.resize(slash + 1);
    exe += "fak.exe";
    if (!file_exists(exe)) return;

    auto store = fb2k::configStore::get();
    const bool first_run = store->getConfigInt(flag_key, 0) == 0;
    auto blob = store->getConfigBlob(formats_key);

    std::vector<entry> list;
    if (blob->size() == 0) {
        if (!first_run) return;
        if (!parse_list(default_entries, sizeof default_entries, default_count, list)) return;
    } else {
        reader r(blob->begin(), blob->size());
        uint32_t count; const uint8_t* rest;
        if (!r.u32(count) || count > 10000 || !r.bytes(blob->size() - 4, rest)) return;
        if (!parse_list(rest, blob->size() - 4, count, list)) return;  // unknown layout: do not touch
    }

    bool changed = false, present = false;
    for (auto& e : list) {
        custom_encoder c;
        if (!parse_custom(e, c) || !is_fak_exe(c.path)) continue;
        present = true;
        if (c.path != exe && !file_exists(c.path)) {
            c.path = exe;
            e = make_custom(c);
            changed = true;
        }
    }
    if (!present && first_run) {
        custom_encoder c;
        c.name = "FAK"; c.path = exe; c.ext = "fak"; c.params = "encode - %d"; c.settings = "default";
        list.push_back(make_custom(c));
        changed = true;
    }
    if (first_run) store->setConfigInt(flag_key, 1);
    if (!changed) return;

    std::vector<uint8_t> out;
    put_u32(out, (uint32_t)list.size());
    for (auto& e : list) { put_guid(out, e.type); put_u32(out, (uint32_t)e.payload.size()); out.insert(out.end(), e.payload.begin(), e.payload.end()); }
    store->setConfigBlob(formats_key, out.data(), out.size());
    FB2K_console_formatter() << "FAK: " << (present ? "updated the FAK encoder path" : "added FAK to the Converter's output formats") << " (" << exe.c_str() << ")";
}

class converter_preset_init : public init_stage_callback {
public:
    void on_init_stage(t_uint32 stage) override {
        // Before foo_converter reads its settings, so the list it loads already contains FAK.
        if (stage != init_stages::before_config_read) return;
        try { install_preset(); } catch (std::exception const& e) { FB2K_console_formatter() << "FAK: converter preset not installed: " << e.what(); }
    }
};
FB2K_SERVICE_FACTORY(converter_preset_init);

